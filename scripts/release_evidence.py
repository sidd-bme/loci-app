"""Generate and validate deterministic macOS release evidence for Loci.

The tool inspects an already-built ``.app`` and, optionally, its distribution
ZIP.  It does not sign, notarize, upload, publish, or modify either artifact.
Public-release validation is deliberately fail-closed: a local ad-hoc package
can produce an evidence report, but it cannot pass the public gate.
"""

